def main():
    from src.data.fetcher import fetcher
    from src.models.predictor import Predictor

    p = Predictor()
    if not p.is_ready:
        print("MODEL_NOT_READY")
        return
    print("ensemble_report:\n" + p.ensemble_report()[:400])

    scores, modes, failed = [], {}, 0
    for i, code in enumerate(CODES, 1):
        try:
            df = fetcher.get_daily_kline(code, start_date="20230101")
            if df is None or len(df) < 120:
                failed += 1
                continue
            pred = p.predict_single(df, code, code, apply_ensemble=True)
            scores.append(float(pred.score))
            modes[pred.model_mode] = modes.get(pred.model_mode, 0) + 1
        except Exception as e:  # noqa: BLE001
            failed += 1
            print(f"  skip {code}: {type(e).__name__}: {str(e)[:80]}")
        if i % 25 == 0:
            print(f"... {i}/{len(CODES)} ok={len(scores)} fail={failed}")
            sys.stdout.flush()

    print(f"\n=== 样本 {len(scores)} 只（失败 {failed}）mode 分布: {modes} ===")
    if not scores:
        return
    scores.sort()
    q = lambda x: scores[int(len(scores) * x)]
    print("min %.1f p10 %.1f p25 %.1f median %.1f p75 %.1f p90 %.1f max %.1f" % (
        scores[0], q(.10), q(.25), q(.50), q(.75), q(.90), scores[-1]))
    print("mean %.2f std %.2f" % (st.mean(scores), st.pstdev(scores)))
    print("--- 候选阈值覆盖率 ---")
    for th in (49, 55, 58, 60, 62, 64, 66, 70):
        print("  >=%d : %.1f%%" % (th, 100 * sum(1 for s in scores if s >= th) / len(scores)))


if __name__ == "__main__":
    main()
